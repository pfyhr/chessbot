// The page: board, controls, and the loop that lets the network answer.

import { Engine } from "./engine.js";
import { Net } from "./net.js";
import { Board } from "./board.js";

const $ = (id) => document.getElementById(id);

const state = {
  engine: null,
  net: null,
  board: null,
  manifest: null,
  humanColor: "white",
  sims: 128,
  considered: 32,
  thinking: false,
  lastMove: null,
  seed: 1,
};

// ---------------------------------------------------------------------------
// Boot
// ---------------------------------------------------------------------------

async function boot() {
  status("Loading the search core…");
  try {
    state.manifest = await (await fetch("model/manifest.json")).json();
    state.engine = await Engine.load("az_wasm.wasm");

    status("Downloading the network…");
    const ref = await (await fetch("model/selfcheck.json")).json();
    state.net = await Net.load("model/gen2600.onnx", {
      obsLen: state.engine.obsLen,
      policyLen: state.engine.policyLen,
      tolerance: ref.tolerance,
      // Opt-in, because on the machines measured so far WebGPU is both less
      // accurate and slower than the wasm kernels for a batch of one.
      prefer: new URLSearchParams(location.search).get("backend"),
      verify: (net) => selfCheck(net, ref),
      onProgress: (got, total) => {
        const pct = total ? Math.round((got / total) * 100) : 0;
        $("bar").style.width = `${pct}%`;
        status(`Downloading the network… ${pct}% (${(got / 1e6).toFixed(1)} MB)`);
      },
    });
    $("loading").classList.add("hidden");
    $("app").classList.remove("hidden");

    const m = state.manifest;
    $("netinfo").textContent =
      `gen${m.gen ?? "?"} · ${m.arch.blocks}x${m.arch.channels} · ` +
      `${(m.params / 1e6).toFixed(1)}M params · ${m.precision} · ${state.net.backend}`;
    if (state.net.unverified) {
      warn(`This browser has no backend that reproduces the network: ` +
           `${state.net.rejected.join("; ")}. The moves below are NOT the ` +
           `trained network's and should not be taken as its play.`);
    } else if (state.net.rejected?.length) {
      // Recovered, so this is information rather than a problem.
      console.info(`fell back to ${state.net.backend}: ${state.net.rejected.join("; ")}`);
    }
    newGame(fromUrl());
  } catch (e) {
    status(`Failed: ${e.message}`);
    console.error(e);
  }
}

/**
 * Verify this backend against numbers produced by the trainer itself.
 *
 * A WebGPU driver that quietly computes something a little different is the
 * failure this is for: everything loads, the board works, and the network is
 * subtly not the one that was trained. The reference values are generated by
 * the same script that gates the build, so they cannot drift apart.
 */
async function selfCheck(net, ref) {
  const eng = state.engine;
  eng.newGame();
  for (const mv of ref.moves) eng.play(mv);
  const { policy, value } = await net.evaluate(eng.encode());
  let worst = Math.abs(value - ref.value);
  for (let i = 0; i < ref.legal.length; i++) {
    worst = Math.max(worst, Math.abs(policy[eng.policyIndex(ref.legal[i])] - ref.logits[i]));
  }
  eng.newGame();
  return worst;
}

// ---------------------------------------------------------------------------
// Game flow
// ---------------------------------------------------------------------------

const cap = (s) => s[0].toUpperCase() + s.slice(1);

/** `?moves=e2e4,h7h6,...` and `?side=black`, so a game can be linked to. */
function fromUrl() {
  const q = new URLSearchParams(location.search);
  const side = q.get("side") === "black" ? "black" : "white";
  const moves = (q.get("moves") ?? "").split(/[,\s]+/).filter(Boolean);
  return { side, moves };
}

function newGame({ moves = [], side = null } = {}) {
  state.engine.newGame();
  if (side) {
    state.humanColor = side;
    const radio = document.querySelector(`input[name=side][value=${side}]`);
    if (radio) radio.checked = true;
  }
  state.lastMove = null;
  state.seed = (Math.random() * 2 ** 31) | 0;
  state.board.setOrientation(state.humanColor);
  clearEval();
  for (const mv of moves) {
    if (!state.engine.play(mv)) {
      warn(`Ignored the rest of the linked game: ${mv} is not legal there.`);
      break;
    }
    state.lastMove = mv;
  }
  refresh();
  // `maybeEngineMove` is a no-op once the game is over, so a linked game that
  // ends in mate stops here rather than being answered.
  maybeEngineMove();
}

function refresh() {
  const e = state.engine;
  const over = e.outcome();
  state.board.setPosition(e.fen, {
    turn: e.turn,
    dests: e.dests(),
    lastMove: state.lastMove,
    check: e.inCheck,
    interactive: !state.thinking && !over && e.turn === state.humanColor,
  });
  renderMoves();
  $("undo").disabled = state.thinking || e.ply === 0;
  $("newgame").disabled = state.thinking;

  if (over) {
    const who = over.kind === "draw"
      ? `Draw by ${over.reason}.`
      : `${cap(over.winner)} wins by ${over.reason}.`;
    const mine = over.kind === "draw" ? ""
      : over.winner === state.humanColor ? " You win." : " The network wins.";
    status(who + mine, true);
  } else if (state.thinking) {
    status("Thinking…");
  } else if (e.turn === state.humanColor) {
    status(e.inCheck ? "Your move — you are in check." : "Your move.");
  }
}

function renderMoves() {
  // SAN, from the core -- it is recorded against the position before each move,
  // which is the only place the information exists.
  const hist = state.engine.historySan();
  const rows = [];
  for (let i = 0; i < hist.length; i += 2) {
    rows.push(`<span class="num">${i / 2 + 1}.</span> ${hist[i]}${hist[i + 1] ? " " + hist[i + 1] : ""}`);
  }
  $("moves").innerHTML = rows.join("  ");
  $("moves").scrollTop = $("moves").scrollHeight;
}

/**
 * Blank the evaluation panel.
 *
 * It describes one search of one position, so the moment the position changes
 * it is stale -- and it was left on screen listing candidate moves that are not
 * even legal any more, which reads as the engine's current opinion.
 */
function clearEval() {
  $("eval").textContent = "—";
  $("lines").replaceChildren();
}

function onHumanMove(uci) {
  const e = state.engine;
  // The board offers squares, not moves; a destination it thought was legal can
  // still be rejected (a pinned piece reached by a different path), and the
  // core is the authority.
  if (!e.play(uci)) { refresh(); return; }
  state.lastMove = uci;
  clearEval();
  refresh();
  maybeEngineMove();
}

async function maybeEngineMove() {
  const e = state.engine;
  if (e.outcome() || e.turn === state.humanColor || state.thinking) return;

  state.thinking = true;
  refresh();
  const started = performance.now();
  try {
    const opts = {
      sims: state.sims,
      considered: state.considered,
      seed: state.seed + e.ply,
      onProgress: (done, total) => status(`Thinking… ${done}/${total}`),
    };
    const res = state.sims === 0
      ? await e.rawBest((obs) => state.net.evaluate(obs))
      : await e.search((obs) => state.net.evaluate(obs), opts);

    const secs = (performance.now() - started) / 1000;
    e.play(res.move);
    state.lastMove = res.move;
    showEval(res, secs);
  } catch (err) {
    warn(`Search failed: ${err.message}`);
    console.error(err);
  } finally {
    state.thinking = false;
    refresh();
  }
}

/**
 * Report the search's opinion in the network's own terms.
 *
 * `value` is P(win) - P(loss) from the side to move; it is shown from White's
 * point of view so it does not flip sign every ply. The per-move table shows
 * the improved policy next to the raw prior, because the gap between them is
 * exactly how much the search disagreed with the network -- the one number
 * that says whether searching was worth anything in this position.
 */
function showEval(res, secs) {
  const mover = state.engine.turn === "white" ? "black" : "white"; // already played
  const white = mover === "white" ? res.value : -res.value;
  const verdict = res.proven
    ? ({ win: "forced win", loss: "forced loss", draw: "forced draw" })[res.proven] +
      ` for ${mover}`
    : `${white >= 0 ? "+" : ""}${white.toFixed(3)} for White`;
  $("eval").textContent =
    `${verdict} · ${res.sims} sims · ${secs.toFixed(1)} s` +
    (res.sims ? ` · ${(res.sims / secs).toFixed(0)} evals/s` : "");

  $("lines").replaceChildren();
  for (const row of res.detail.slice(0, 6)) {
    const li = document.createElement("li");
    li.innerHTML =
      `<b>${row.m}</b>` +
      `<span class="bar"><i style="width:${(row.p * 100).toFixed(1)}%"></i></span>` +
      `<span class="n">${(row.p * 100).toFixed(1)}%</span>` +
      `<span class="dim">prior ${(row.prior * 100).toFixed(1)}% · ` +
      `${row.n} visits${row.q === null ? "" : ` · q ${row.q >= 0 ? "+" : ""}${row.q.toFixed(2)}`}</span>`;
    $("lines").append(li);
  }
}

// ---------------------------------------------------------------------------
// Controls
// ---------------------------------------------------------------------------

/**
 * Both status elements: `#bootstatus` while loading, `#status` once the board
 * is up. Writing to only one of them is how the game result ended up invisible.
 */
function status(msg, over = false) {
  for (const id of ["bootstatus", "status"]) {
    const el = $(id);
    if (!el) continue;
    el.textContent = msg;
    if (id === "status") el.classList.toggle("over", over);
  }
}
function warn(msg) { $("warn").textContent = msg; $("warn").classList.remove("hidden"); }

function wire() {
  state.board = new Board($("board"), { onMove: onHumanMove });

  $("newgame").addEventListener("click", () => newGame());
  $("flip").addEventListener("click", () => state.board.flip());
  $("undo").addEventListener("click", () => {
    if (state.thinking) return;
    // Back to the human's own move, not merely one ply: undoing a single ply
    // hands the position straight back to the network, which just replays.
    state.engine.undo();
    while (state.engine.ply > 0 && state.engine.turn !== state.humanColor) {
      state.engine.undo();
    }
    state.lastMove = null;
    clearEval();
    refresh();
    // Taking back to the very start while playing Black leaves the network on
    // move, so it needs waking up again.
    maybeEngineMove();
  });

  for (const el of document.querySelectorAll("input[name=side]")) {
    el.addEventListener("change", () => {
      state.humanColor = el.value;
      newGame();
    });
  }

  const sims = $("sims");
  const SIM_STEPS = [0, 8, 16, 32, 64, 128, 256, 512, 1024];
  sims.max = String(SIM_STEPS.length - 1);
  const showSims = () => {
    state.sims = SIM_STEPS[Number(sims.value)];
    $("simval").textContent = state.sims === 0 ? "raw policy (no search)" : `${state.sims} sims`;
  };
  sims.addEventListener("input", showSims);
  sims.value = String(SIM_STEPS.indexOf(128));
  showSims();
}

wire();
boot();
